def key_of(path: Path) -> str:
    return path.name.split("-")[0].replace("第", "第")  # 第01章 etc.


def apply_file(path: Path, stats: dict) -> None:
    key = path.stem.split("-")[0]
    text = path.read_text(encoding="utf-8")
    original = text
    local = {"exact": 0, "block": 0, "rank": 0, "note": 0, "boundary": 0, "heading": 0}

    # 1) 段落级替换
    for start, end, new in BLOCKS.get(key, []):
        si = text.find(start)
        if si < 0:
            print(f"  ⚠️  [{key}] 段落起点未命中: {start[:36]}")
            continue
        ei = text.find(end, si + len(start))
        if ei < 0:
            print(f"  ⚠️  [{key}] 段落终点未命中: {end[:36]}")
            continue
        text = text[:si] + new + text[ei:]
        local["block"] += 1

    # 2) 精确替换
    for old, new in EXACT.get(key, []):
        n = text.count(old)
        if n == 0:
            print(f"  ⚠️  [{key}] 精确规则未命中: {old[:40]}")
            continue
        text = text.replace(old, new)
        local["exact"] += n

    # 3) 全局框架词
    for old, new in [
        ("原型底色与神经底盘", "原型底色与认知偏好"),
        ("双环演进定律", "双环探索框架"),
        ("同源四阶微循环", "同源四态观察"),
        ("神经校准提问", "回顾提问"),
        ("出厂布线", "相对稳定的认知偏好"),
        ("自我姿态", "决策姿态"),
        ("变化偏好", "变化策略"),
        ("晚间神经校准", "晚间回顾"),
    ]:
        n = text.count(old)
        if n:
            text = text.replace(old, new)
            local["heading"] += n

    # 4) 名次改写
    lines = text.split("\n")
    out_lines = []
    for line in lines:
        new_line, hit = rewrite_rarity(line)
        local["rank"] += hit
        out_lines.append(new_line)
    text = "\n".join(out_lines)

    # 5) 阅读说明（16 个图鉴章，放在首个 # 标题之后）
    if key not in BOUNDARY and not text.startswith("# "):
        pass
    if key not in BOUNDARY and READING_NOTE.strip() not in text:
        lines = text.split("\n")
        for i, line in enumerate(lines):
            if line.startswith("# "):
                lines.insert(i + 1, "\n" + READING_NOTE)
                local["note"] += 1
                break
        text = "\n".join(lines)

    # 6) 章末「研究证据与模型边界」栏目（理论卷 + 实操卷）
    if key in BOUNDARY and "## 研究证据与模型边界" not in text:
        text = text.rstrip() + "\n" + BOUNDARY_TEMPLATE.format(
            topic=BOUNDARY[key], refs=REFS[key]
        )
        local["boundary"] += 1

    if text != original:
        # 固定写 LF：Windows 下 write_text 会转成 CRLF，破坏 extract-book-data.mjs
        # 里 `\n\n饭局` 这类段落锚点，导致 chinaSlices 抽取为空。
        path.write_bytes(text.encode("utf-8"))
        stats["files"] += 1
        for k, v in local.items():
            stats[k] += v
        print(f"  ✓ {path.name}: " + ", ".join(f"{k}={v}" for k, v in local.items() if v))


def main() -> None:
    stats = {"files": 0, "exact": 0, "block": 0, "rank": 0, "note": 0, "boundary": 0, "heading": 0}
    print("📖 P0 书稿改写开始\n")
    for vol in VOLS:
        for p in sorted((BOOK / vol).glob("第*章-*.md")):
            apply_file(p, stats)
    print("\n📊 汇总:", json.dumps(stats, ensure_ascii=False))
    print("\n⚠️  如有「未命中」告警，请核对原文后补规则，不要忽略。")


if __name__ == "__main__":
    main()
