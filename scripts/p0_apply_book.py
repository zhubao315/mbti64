CODE_RE = re.compile(r"`?([A-Z]{4}-[AC]-[OH])`?")
RANK_RE = re.compile(r"第\d+/64(?:（[\d.]+‰）)?")
PER_RE = re.compile(r"，?每千人约?[\d.]+人")


def rewrite_rarity(line: str) -> tuple[str, int]:
    """把单一名次改为「档位 + 每千人数值」，数值一律取权威表。"""
    if "第" not in line or "/64" not in line:
        return line, 0
    m = CODE_RE.search(line)
    if not m or m.group(1) not in BY_CODE:
        return line, 0
    rec = BY_CODE[m.group(1)]
    replacement = f'{rec["tier"]}，每千人约{rec["per1000"]}人'

    if line.lstrip().startswith("### 第"):
        head = line.split("——")[0].rstrip()
        return f"{head} —— {replacement}", 1

    new = RANK_RE.sub(replacement, line)
    # 四态标题以外若同时写了每千人数值，去掉重复的一份
    if new != line:
        new = PER_RE.sub("", new) if new.count("每千人约") > 1 else new
        return new, 1
    return line, 0


