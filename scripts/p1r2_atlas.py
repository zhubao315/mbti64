from __future__ import annotations

import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent / "书-千分之一的你"
FILES: dict[str, pathlib.Path] = {}
for p in ROOT.rglob("*.md"):
    FILES.setdefault(p.name, p)

STATS = {"line": 0, "sub": 0, "miss": []}


def read(name: str) -> str:
    return FILES[name].read_text(encoding="utf-8")


def write(name: str, text: str) -> None:
    FILES[name].write_bytes(text.encode("utf-8"))


def sub(name: str, old: str, new: str, label: str) -> None:
    t = read(name)
    if old not in t:
        if new in t:
            return
        STATS["miss"].append(label)
        print(f"  ⚠️ 未命中 [sub] {label}")
        return
    n = t.count(old)
    write(name, t.replace(old, new))
    STATS["sub"] += n
    print(f"  ✓ {label}: {n} 处")


def line(name: str, prefix: str, new: str, label: str) -> None:
    """按行首前缀定位唯一整行并替换；已是新文案则幂等跳过。"""
    t = read(name)
    rx = re.compile(r"(?m)^" + re.escape(prefix) + r".*$")
    ms = list(rx.finditer(t))
    if len(ms) != 1:
        # 首次改写后行首前缀可能已消失；新文案已落地即视为幂等成功
        if new in t:
            return
        STATS["miss"].append(label)
        print(f"  ⚠️ 前缀命中 {len(ms)} 行 [line] {label}")
        return
    old = ms[0].group()
    if old.strip() == new.strip():
        return
    write(name, t[: ms[0].start()] + new + t[ms[0].end() :])
    STATS["line"] += 1
    print(f"  ✓ {label}")


