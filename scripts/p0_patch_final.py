CODE_RE = re.compile(r"`?([A-Z]{4}-[AC]-[OH])`?")
POP_RE = re.compile(r"每一千个人里只有[^，—]{0,14}能同时保持")


def apply_population_rewrite():
    for p in CHAPTERS:
        t = p.read_text(encoding="utf-8")
        lines = t.split("\n")
        changed = False
        for i, line in enumerate(lines):
            if not POP_RE.search(line):
                continue
            codes = CODE_RE.findall(line)
            code = codes[0] if codes else ""
            rec = BY_CODE.get(code, {})
            tier = rec.get("tier", "塔尖")
            per = rec.get("per1000", "")
