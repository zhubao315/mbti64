def apply_line_rewrites():
    for name, prefix, new in REWRITES:
        p = FILES.get(name)
        if p is None:
            stats["miss"].append(f"[{name}] 文件不存在")
            continue
        t = p.read_text(encoding="utf-8")
        # 幂等：目标文本已在文件中则跳过，避免重复执行时产生大量伪告警
        if new.strip() in t:
            continue
        pat = re.compile(r"(?m)^" + re.escape(prefix) + r".*$")
        t2, n = pat.subn(lambda m: new, t, count=1)
        if n == 0:
            stats["miss"].append(f"[{name}] 行首未命中: {prefix[:38]}")
            continue
        p.write_bytes(t2.encode("utf-8"))  # 固定 LF
        stats["line"] += n


