def f(key: str) -> Path:
    for p in BOOK.glob(f"0*/第{key}章-*.md"):
        return p
    raise FileNotFoundError(key)


def sub(key: str, old: str, new: str, label: str) -> None:
    p = f(key)
    t = p.read_text(encoding="utf-8")
    n = t.count(old)
    if n == 0:
        print(f"  ⚠️  [{key}] 未命中: {label}")
        return
    p.write_bytes(t.replace(old, new).encode("utf-8"))  # 固定 LF
    print(f"  ✓ [{key}] {label} × {n}")


def block(key: str, start: str, end: str, new: str, label: str) -> None:
    p = f(key)
    t = p.read_text(encoding="utf-8")
    si, ei = t.find(start), t.find(end)
    if si < 0 or ei < 0 or ei <= si:
        print(f"  ⚠️  [{key}] 段落锚点失败: {label} (start={si}, end={ei})")
        return
    p.write_bytes((t[:si] + new + t[ei:]).encode("utf-8"))  # 固定 LF
    print(f"  ✓ [{key}] {label}")


