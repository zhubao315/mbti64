from __future__ import annotations

import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent / "书-千分之一的你"

# 用文件名定位（章节分布在 6 个卷目录下）
FILES: dict[str, pathlib.Path] = {}
for p in ROOT.rglob("*.md"):
    FILES.setdefault(p.name, p)

stats = {"sub": 0, "line": 0, "skip": 0, "miss": []}


def get(name: str) -> pathlib.Path:
    if name not in FILES:
        raise FileNotFoundError(name)
    return FILES[name]


def read(name: str) -> str:
    return get(name).read_text(encoding="utf-8")


def write(name: str, text: str) -> None:
    get(name).write_bytes(text.encode("utf-8"))  # 固定 LF


def sub(name: str, old: str, new: str, label: str, count: int = 0) -> None:
    """精确字符串替换；若 new 已存在且 old 不存在，视为已处理。"""
    t = read(name)
    if old not in t:
        if new in t:
            stats["skip"] += 1
            return
        stats["miss"].append(f"[{name}] 未命中: {label}")
        return
    n = t.count(old) if count == 0 else count
    write(name, t.replace(old, new, n if n else -1))
    stats["sub"] += n if n else 1


def line(name: str, prefix: str, new: str, label: str) -> None:
    """按行首前缀整行替换；若新文本已存在则跳过。"""
    t = read(name)
    if new in t:
        stats["skip"] += 1
        return
    pat = re.compile(r"(?m)^" + re.escape(prefix) + r".*$")
    t2, n = pat.subn(lambda _m: new, t, count=1)
    if n == 0:
        stats["miss"].append(f"[{name}] 整行未命中: {label}")
        return
    write(name, t2)
    stats["line"] += 1


