def main() -> int:
    total_hits = 0
    zero: list[str] = []
    rules = CROSS + FIXES + HEADERS
    for label, old, new in rules:
        hits = 0
        files = 0
        for p in TARGETS:
            t = p.read_text(encoding="utf-8")
            if old in t:
                n = t.count(old)
                p.write_bytes(t.replace(old, new).encode("utf-8"))
                hits += n
                files += 1
            # 已是新文案 → 幂等跳过；本章没有该句式 → 正常
        if hits:
            total_hits += hits
            print(f"  ✓ {label}: {hits} 处 / {files} 章")
        else:
            already = any(new in p.read_text(encoding="utf-8") for p in TARGETS)
            zero.append(label)
            print(f"  {'✓ 已是新文案' if already else '⚠️ 0 命中'}: {label}")

    print(f"\n跨章模板：{len(rules)} 条规则，命中 {total_hits} 处；"
          f"0 命中 {len(zero)} 条")
    if zero:
        print("  0 命中明细：" + "、".join(zero))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
