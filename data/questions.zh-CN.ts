/** 交错排题：EI → SN → TF → JP → AC → OH 循环，避免同一维度连问、也降低套路作答 */
function interleave(questions: Question[]): Question[] {
  const buckets = DIM_ORDER.map((k) => questions.filter((q) => q.dim === k));
  const out: Question[] = [];
  let moved = true;
  while (moved) {
    moved = false;
    for (const bucket of buckets) {
      const next = bucket.shift();
      if (next) {
        out.push(next);
        moved = true;
      }
    }
  }
  return out;
}

export const SESSION_ORDER: Record<Mode, Question[]> = {
  quick: interleave(CORE_QUESTIONS),
  full: interleave(ALL_QUESTIONS),
};

export function getSessionOrder(mode: Mode): Question[] {
  return SESSION_ORDER[mode];
}

