import { DIMS, DIM_ORDER, type DimKey, type ItemSet, type Mode, type Question, type Scene } from "./schema";

/* -------------------------------------------------------------------------
 * 题型构造器（让 120 道题保持可读、可审计）
 * L = Likert 五级；B = 情景二选一（option A 恒为 poleA 侧）；IMG = 四选一图片题
 * ---------------------------------------------------------------------- */

function L(id: string, dim: DimKey, set: ItemSet, scene: Scene, text: string, reverse = false, hint?: string): Question {
  return { id, dim, type: "likert", scene, set, text, ...(reverse ? { reverse: true as const } : {}), ...(hint ? { hint } : {}) };
}

function B(id: string, dim: DimKey, set: ItemSet, scene: Scene, text: string, aLabel: string, bLabel: string, hint?: string): Question {
  return {
    id,
    dim,
    type: "binary",
    scene,
    set,
    text,
    ...(hint ? { hint } : {}),
    choices: [
      { label: aLabel, pole: DIMS[dim].poleA },
      { label: bLabel, pole: DIMS[dim].poleB },
    ],
  };
}

/** cards 顺序即展示顺序；side "A" = poleA 侧，"B" = poleB 侧 */
function IMG(
  id: string,
  dim: DimKey,
  set: ItemSet,
  scene: Scene,
  text: string,
  cards: Array<[string, string, "A" | "B"]>,
  hint?: string,
): Question {
  return {
    id,
    dim,
    type: "image",
    scene,
    set,
    text,
    ...(hint ? { hint } : {}),
    choices: cards.map(([emoji, label, side]) => ({
      emoji,
      label,
      pole: side === "A" ? DIMS[dim].poleA : DIMS[dim].poleB,
    })),
  };
}

